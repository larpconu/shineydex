// Copies third-party files into public/ so the app needs no build step and works offline.
// Run after changing versions: npm run vendor
import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const nm = (p) => new URL(`../node_modules/${p}`, import.meta.url);
const pub = (p) => new URL(`../public/${p}`, import.meta.url);

mkdirSync(pub('vendor/leaflet/images'), { recursive: true });
for (const f of ['leaflet.js', 'leaflet.css']) cpSync(nm(`leaflet/dist/${f}`), pub(`vendor/leaflet/${f}`));
cpSync(nm('@supabase/supabase-js/dist/umd/supabase.js'), pub('vendor/supabase.js'));

mkdirSync(pub('fonts'), { recursive: true });
const fonts = [
  ['space-grotesk', 'space-grotesk-latin-700-normal'],
  ['space-grotesk', 'space-grotesk-latin-500-normal'],
  ['inter', 'inter-latin-400-normal'],
  ['inter', 'inter-latin-500-normal'],
  ['inter', 'inter-latin-600-normal'],
  ['jetbrains-mono', 'jetbrains-mono-latin-700-normal'],
];
for (const [pkg, f] of fonts) cpSync(nm(`@fontsource/${pkg}/files/${f}.woff2`), pub(`fonts/${f}.woff2`));

// Lucide icons (ISC license) → one small JS module of inner SVG markup.
const icons = ['ghost', 'radar', 'users', 'log-in', 'circle-help', 'settings', 'map', 'radio', 'ellipsis', 'share', 'copy',
  'crosshair', 'shield', 'eye-off', 'eye', 'check', 'x', 'chevron-left', 'chevron-right', 'trash-2', 'flag', 'ban', 'user-x',
  'timer', 'zap', 'navigation', 'bell', 'bell-off', 'moon', 'sun-dim', 'lock', 'mail', 'trophy', 'door-open', 'shuffle',
  'footprints', 'target', 'send', 'play', 'square', 'circle-alert', 'locate-fixed', 'wifi-off', 'refresh-cw', 'smartphone',
  'volume-x', 'hand', 'skull', 'party-popper', 'user', 'at-sign', 'pencil', 'log-out', 'info', 'bot', 'flask-conical',
  'fast-forward', 'circle-check', 'circle-x', 'map-pin', 'plus', 'minus', 'clock', 'scan-eye', 'life-buoy', 'download', 'key-round'];
const out = {};
for (const name of icons) {
  const svg = readFileSync(nm(`lucide-static/icons/${name}.svg`), 'utf8');
  out[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
writeFileSync(pub('js/icon-data.js'),
  '// Generated by scripts/vendor.mjs from lucide-static (ISC license). Do not edit.\nexport default ' + JSON.stringify(out, null, 0) + ';\n');
console.log('vendored', Object.keys(out).length, 'icons');
